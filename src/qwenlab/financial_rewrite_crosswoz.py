def _history(text):
    if not text:
        return []
    return [{'role':{'u':'user','a':'assistant'}[item[0]],'content':item[2:]} for item in text.split('||')]


def _target(code, message):
    state={'authenticated': True}
    if code in {'P','L','C'}:
        tool={'P':'queryLoanProducts','L':'queryMyApplications','C':'queryMyCreditScore'}[code]
        return state,label('tool','需要当前产品或本人账户的实时记录，使用现有只读工具；不预判审批结果。',tool=tool)
    if code.startswith('D'):
        number=int(code[1:]);state['application_id']=number
        return state,label('tool','新合成请求明确给出本人申请编号，可信模拟状态一致；执行时仍须验证归属。',tool='queryApplicationDetail',arguments={'applicationId':number})
    if code.startswith('S'):
        number=int(code[1:]);state['status_code']=number
        return state,label('tool','请求解释当前明确给出的平台状态码，调用已有状态解释工具。',tool='explainApplicationStatus',arguments={'status':number})
    if code=='R':
        collection='privacy_policy' if any(w in message for w in ['隐私','保存多久','保留多久','保存期限']) else 'loan_service_docs'
        return state,label('retrieve','需要平台具体的正式规则或流程，输入未提供答案，应检索可用知识集合。',collection=collection)
    if code=='Q':
        return state,label('clarify','指代、对象或问题细节不足，现有上下文不能唯一确定下一步请求。',slots=['request_details'])
    if code=='A':
        return state,label('answer','只解释已给文字或一般概念，不需要编造平台条款或查询个人账务。')
    if code=='H':
        return state,label('human','明确人工诉求或正在发生的账户/资金争议需要升级；当前未接通人工，不可声称已经转接。')
    if code=='F':
        return state,label('refuse','改写中明确新增越权获取、伪造材料或绕过授权的请求，拒绝该具体操作。原旅游请求本身并不违规。')
    if code=='Z':
        return state,label('close','用户明确说明问题已解决或结束本次咨询，结束会话不等于撤销申请。')
    raise ValueError(code)


