def create_records():
    records, story_names, record_codes = [], {}, {}
    group_no = 0
    for cohort, source in [('current-service', CURRENT + MORE),
                           ('planned-retrieval', PLANNED), ('preauth-robustness', PREAUTH)]:
        for line in source.strip().splitlines():
            if not line.strip():
                continue
            group_no += 1
            title, *entries = line.split('|')
            gid = f'SEB-G{group_no:03d}'
            story_names[gid] = title
            assert 1 <= len(entries) <= 4
            for variant, entry in enumerate(entries, 1):
                directive, message = entry.split(':', 1)
                restrictions = directive.split('!')
                head, unavailable = restrictions[0], restrictions[1:]
                parts = head.split('@')
                code, modifier = parts[0], parts[1] if len(parts) > 1 else None
                state = {}
                if modifier == 'id': state['pending'] = 'applicationId'
                elif modifier == 'status': state['pending'] = 'statusCode'
                elif modifier and modifier.startswith('selected'):
                    state['selectedApplicationId'] = int(modifier.removeprefix('selected'))
                elif modifier: raise ValueError(modifier)
                context = {'message': message, 'authenticated': cohort != 'preauth-robustness',
                           'history': [{'role': r, 'content': c} for r, c in HISTORIES.get(title, [])],
                           'state': state}
                if unavailable:
                    context['availableTools'] = [t for t in TOOLS.values() if t not in {OMIT[x] for x in unavailable}]
                if cohort == 'preauth-robustness':
                    context['availableTools'] = []
                layer = {'current-service': 'node-projection', 'planned-retrieval': 'planned-capability-component',
                         'preauth-robustness': 'preauth-component'}[cohort]
                record = {
                    'id': f'{gid}-{variant}', 'source_group': gid, 'cohort': cohort, 'input_layer': layer,
                    'context': context, 'expected_action': 'tool' if code in TOOLS else ACTION[code],
                    'expected_tool': TOOLS.get(code), 'tool_arguments': {},
                    'missing_slots': [MISSING[code]] if code in MISSING else [],
                    'retrieval_collection': ('privacy_policy' if code == 'K' else 'loan_service_docs') if code in ('k', 'K') else None,
                    'label_reason': f'{title}：{REASONS[code]}',
                }
                records.append(record)
                record_codes[record['id']] = code
    # One independently worded variant per story at the component boundary. State-dependent
    # numeric/selected-item replies stay in the Node projection cohort.
    picked_groups = set()
    for record in records:
        if (record['cohort'] == 'current-service' and len(picked_groups) < 142
                and record['source_group'] not in picked_groups and not record['context']['state']):
            record['input_layer'] = 'component-message-only'
            picked_groups.add(record['source_group'])
    return records, story_names, record_codes

def check_parameters(records):
    backend = pathlib.Path(__file__).resolve().parents[3] / 'uestc_Integrated_Design' / '后端' / 'services' / 'customerSupport' / 'parameters.js'
    # Only the pure parser is imported; this does not import tools, connect to storage,
    # perform inference, or contact a remote service.
    js = """
const fs = require('fs');
const p = require(process.argv[1]);
const rows = JSON.parse(fs.readFileSync(0, 'utf8'));
process.stdout.write(JSON.stringify(rows.map(x => ({id:x.id,
  ref:p.applicationReference(x.context), codes:p.statusCodes(x.context),
  bodyRef:p.applicationReference({...x.context,state:{}}),
  bodyCodes:p.statusCodes({...x.context,state:{}})}))));
"""
    result = subprocess.run(['node', '-e', js, str(backend)], input=json.dumps(records, ensure_ascii=False),
                            text=True, encoding='utf-8', capture_output=True, check=True)
    parsed = {item['id']: item for item in json.loads(result.stdout)}
    for row in records:
        p = parsed[row['id']]
        if row['expected_tool'] == 'queryApplicationDetail':
            assert p['ref']['id'] and not p['ref']['ambiguous'], (row['id'], row['context'], p)
            row['tool_arguments'] = {'applicationId': p['ref']['id']}
            if row['input_layer'] == 'component-message-only':
                assert p['bodyRef'] == p['ref'], (row['id'], p)
        elif row['expected_tool'] == 'explainApplicationStatus':
            assert len(p['codes']) == 1 and p['codes'][0] in (0, 1, 2), (row['id'], p)
            row['tool_arguments'] = {'status': p['codes'][0]}
            if row['input_layer'] == 'component-message-only':
                assert p['bodyCodes'] == p['codes'], (row['id'], p)
        if row['expected_action'] == 'tool':
            assert row['context']['authenticated']
            assert row['expected_tool'] in row['context'].get('availableTools', TOOLS.values())
        if row['missing_slots'] == ['applicationId']:
            assert p['ref']['id'] is None, (row['id'], p)
        if row['missing_slots'] == ['statusCode']:
            assert len(p['codes']) != 1 or p['codes'][0] not in (0, 1, 2), (row['id'], p)
    return parsed

def main():
    records, names, codes = create_records()
    assert len(records) == 760
    assert len(names) == 191
    parsed = check_parameters(records)
    assert len({r['id'] for r in records}) == len(records)
    assert len({r['context']['message'] for r in records}) == len(records)
    assert collections.Counter(r['cohort'] for r in records) == {'current-service': 570, 'planned-retrieval': 114, 'preauth-robustness': 76}
    fields = ['id', 'source_group', 'cohort', 'input_layer', 'context', 'expected_action', 'expected_tool',
              'tool_arguments', 'missing_slots', 'retrieval_collection', 'label_reason']
    for record in records:
        assert list(record) == fields
        assert set(record['context']) <= {'message', 'authenticated', 'history', 'state', 'availableTools'}
        assert set(record['context']['state']) <= {'pending', 'selectedApplicationId'}
        assert len(record['context']['history']) <= 4
        assert len(record['context']['message']) <= 2000
        assert sum(len(h['content']) for h in record['context']['history']) <= 800
        assert not (record['cohort'] == 'current-service' and record['expected_action'] == 'retrieve')
    directory = pathlib.Path(__file__).resolve().parent
    (directory / 'batch-b.authoring.json').write_text(json.dumps(records, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    contrast = sum(len({r['expected_action'] for r in records if r['source_group'] == gid}) > 1 for gid in names)
    stats = {'records': len(records), 'source_groups': len(names), 'contrast_groups': contrast,
             'actions': dict(collections.Counter(r['expected_action'] for r in records)),
             'layers': dict(collections.Counter(r['input_layer'] for r in records)),
             'tools': dict(collections.Counter(r['expected_tool'] for r in records if r['expected_tool'])),
             'with_history': sum(bool(r['context']['history']) for r in records),
             'stateful': sum(bool(r['context']['state']) for r in records),
             'explicit_capability_subset': sum('availableTools' in r['context'] for r in records)}
    print(json.dumps(stats, ensure_ascii=False, indent=2))

if __name__ == '__main__':
    main()
